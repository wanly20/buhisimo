#!/usr/bin/env node
// Build js/worldmap-data.js from Natural Earth 1:50m country shapes (public domain),
// as packaged by world-atlas@2.0.2 (countries-50m.json, TopoJSON):
//   curl -L -o countries-50m.json https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-50m.json
//   node prototype/tools/make_worldmap.mjs countries-50m.json
// Equirectangular projection in tenths of a degree: x = (lon + 180) * 10, y = (90 - lat) * 10.
// Shapes are simplified (Douglas-Peucker) and tiny islands dropped, except for the
// countries the lessons use. Antarctica is left out.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const src = process.argv[2];
if (!src) { console.error("usage: node make_worldmap.mjs countries-50m.json"); process.exit(2); }
const topo = JSON.parse(readFileSync(src, "utf8"));
const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "js", "worldmap-data.js");

// ISO numeric id -> our code. These are drawn as separate, highlightable shapes.
const FOCUS = {
  "032": "ar", "152": "cl", "604": "pe", "170": "co", "192": "cu", "840": "us", "214": "do",
  "226": "gq", "724": "es", "608": "ph", "036": "au",
};
// Other countries where Spanish is an official language: tinted, not tappable.
const HISPANIC = ["484", "320", "340", "222", "558", "188", "591", "862", "218", "068", "600", "858", "630"];

const { scale: [kx, ky], translate: [tx, ty] } = topo.transform;
const arcs = topo.arcs.map((arc) => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => { x += dx; y += dy; return [x * kx + tx, y * ky + ty]; });
});
const ring = (ids) => {
  const pts = [];
  for (const i of ids) {
    const a = i < 0 ? [...arcs[~i]].reverse() : arcs[i];
    pts.push(...(pts.length ? a.slice(1) : a));
  }
  return pts;
};

function dp(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [x1, y1] = pts[a], [x2, y2] = pts[b];
    const dx = x2 - x1, dy = y2 - y1, len = Math.hypot(dx, dy) || 1e-9;
    let best = -1, bi = -1;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / len;
      if (d > best) { best = d; bi = i; }
    }
    if (best > tol) { keep[bi] = 1; stack.push([a, bi], [bi, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
const area = (pts) => Math.abs(pts.reduce((s, [x, y], i) => { const [x2, y2] = pts[(i + 1) % pts.length]; return s + x * y2 - x2 * y; }, 0) / 2);

function pathOf(geom, { tol, minArea }) {
  const polys = geom.type === "Polygon" ? [geom.arcs] : geom.type === "MultiPolygon" ? geom.arcs : [];
  let d = "";
  for (const poly of polys) {
    poly.forEach((r, k) => {
      const pts = ring(r);
      if (pts.some((p, i) => i && Math.abs(p[0] - pts[i - 1][0]) > 180)) return; // crosses the antimeridian (Fiji, Chukotka): left out
      if (k === 0 && area(pts) < minArea) return;
      if (k > 0 && area(pts) < minArea * 4) return;
      const mid = pts.length >> 1; // closed ring: simplify the two halves separately
      const s = [...dp(pts.slice(0, mid + 1), tol).slice(0, -1), ...dp(pts.slice(mid), tol)];
      if (s.length < 3) return;
      const xy = s.map(([lon, lat]) => [Math.round((lon + 180) * 10), Math.round((90 - lat) * 10)]);
      const ded = xy.filter((p, i) => i === 0 || p[0] !== xy[i - 1][0] || p[1] !== xy[i - 1][1]);
      if (ded.length < 3) return;
      d += `M${ded[0][0]} ${ded[0][1]}l` + ded.slice(1).map(([x, y], i) => `${x - ded[i][0]} ${y - ded[i][1]}`).join(" ") + "z";
    });
  }
  return d.replace(/ -/g, "-");
}

const countries = {}, hisp = [], rest = [];
for (const g of topo.objects.countries.geometries) {
  const id = g.id, name = g.properties?.name;
  if (name === "Antarctica") continue;
  if (FOCUS[id]) countries[FOCUS[id]] = (countries[FOCUS[id]] || "") + pathOf(g, { tol: 0.06, minArea: 0.004 }); // ids repeat (036 = Australia + Ashmore Is.)
  else if (HISPANIC.includes(id)) hisp.push(pathOf(g, { tol: 0.1, minArea: 0.05 }));
  else rest.push(pathOf(g, { tol: 0.18, minArea: 0.6 }));
}

const out = `// Generated by tools/make_worldmap.mjs from Natural Earth 1:50m (public domain,
// via world-atlas@2.0.2). Do not edit by hand. Coordinates: x = (lon + 180) * 10,
// y = (90 - lat) * 10 (equirectangular, tenths of a degree).
export const WORLD = {
  land: ${JSON.stringify(rest.join(""))},
  hispanic: ${JSON.stringify(hisp.join(""))},
  countries: ${JSON.stringify(countries, null, 1)},
};
`;
writeFileSync(OUT, out);
console.log(`wrote ${OUT}: ${(out.length / 1024).toFixed(1)} KB`);
